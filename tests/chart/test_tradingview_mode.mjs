import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const ctx={window:{},document:{documentElement:{dataset:{theme:'light'}}}};
vm.runInNewContext(readFileSync('docs/tradingview-mode.js','utf8'),ctx);
const tv=ctx.window.ICTradingView;
for (const [s,want] of [['BTC-USD','BINANCE:BTCUSDT'],['ETH-USD','BINANCE:ETHUSDT'],['BTC/USDT','BINANCE:BTCUSDT'],['BRK-B','BRK.B'],['GC=F','COMEX:GC1!'],['BZ=F','ICEEUR:BRN1!'],['NASDAQ:AAPL','NASDAQ:AAPL'],['SPY','SPY']]) assert.equal(tv.symbol(s),want);
for (const s of ['',null,'<script>','AAPL&x=1']) assert.equal(tv.symbol(s),null);
for(const [tf,want] of [['1m','1'],['4H','240'],['W','W'],['D','D']]) assert.equal(tv.interval(tf),want);
const cfg=tv.config({symbol:'BTC-USD',tf:'4H'});
assert.equal(cfg.hide_side_toolbar,false);assert.equal(cfg.hide_top_toolbar,false);
assert.equal(cfg.theme,'light');assert.equal(cfg.symbol,'BINANCE:BTCUSDT');
assert.equal(cfg.interval,'240');assert.equal(cfg.allow_symbol_change,true);
console.log('TradingView symbol mapping and widget configuration passed');
